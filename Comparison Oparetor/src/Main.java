// JAVA Operator    Comparison operator
public class Main
{
    public static void main(String[] args)
    {
        int x = 10;
        System.out.println(x);
        int y = 20;
        System.out.println(y);
        System.out.println(x==y);
        System.out.println(x<y);
        System.out.println(x>y);
        System.out.println(x>=y);
        System.out.println(x<=y);
        System.out.println(x!=y);
    }
}
