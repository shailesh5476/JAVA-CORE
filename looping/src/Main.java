//Looping in JAVA
public class Main
{
    public static void main(String[] args)
    {
        int a =0;
        System.out.println(a);
        while(a<10);
        {
            System.out.println(a);
            a++;
            System.out.println(a);
        }

        //OR DO WHILE LOOP
        int b = 1;
        System.out.println(b);
        do
        {
            System.out.println(b);
            b++;
            System.out.println(b);
        }
        while(b<10);


    }
}